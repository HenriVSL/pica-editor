#!/usr/bin/env python3
"""Generate tests/data/codec/ (reference vectors for the codec, detect and ucd suites). Owner: T02.
  python3 tools/gen_testdata.py          (also: make -C tests data)

Files (deterministic; Python's codecs/unicodedata are the reference):
  sbcs.txt        per code page "cp N" + 256 tokens: decoded code point in hex, or "-" for an undefined byte
  cp932.bin       DBCS test provider: "P932", u16 LE singles[256] (0xFFFF = lead byte, 0xFFFE = undefined), then for
                  each lead byte in ascending order 256 u16 LE (decoded pair, 0 = invalid pair)
  utf8.txt        random strict-UTF-8 cases: "<bytes hex | .> <ecp list | .>"; bad bytes as 0x110000 + byte
  utf16.txt       random UTF-16 cases: "le|be <bytes hex | .> <ecp list | .>"; lone surrogates as 0x120000 + unit,
                  a final odd byte as 0x110000 + byte
  ucd_blocks.txt  per 256-code-point block "BBBB HHHHHHHH": checksum of width/fold/upper/lower/word (tools/gen_ucd.py)
"""
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_cptables  # noqa: E402
import gen_ucd       # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'tests', 'data', 'codec')


def write_text(name, lines):
    with open(os.path.join(OUT, name), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def gen_sbcs():
    lines = ['# generated by tools/gen_testdata.py: SBCS decode vectors from Python %s' % sys.version.split()[0]]
    for cp in gen_cptables.CODEPAGES:
        tbl = gen_cptables.decode_table(cp)
        lines.append('cp %d' % cp)
        for i in range(0, 256, 16):
            lines.append(' '.join('-' if v is None else '%X' % v for v in tbl[i:i + 16]))
    write_text('sbcs.txt', lines)


def gen_cp932():
    singles = []
    leads = []
    for b in range(256):
        try:
            s = bytes([b]).decode('cp932')
            singles.append(ord(s) if len(s) == 1 else 0xFFFE)
        except UnicodeDecodeError:
            # either a lead byte (some trail makes a valid pair) or undefined
            ok = False
            for t in range(256):
                try:
                    if len(bytes([b, t]).decode('cp932')) == 1:
                        ok = True
                        break
                except UnicodeDecodeError:
                    pass
            singles.append(0xFFFF if ok else 0xFFFE)
            if ok:
                leads.append(b)
    out = bytearray(b'P932')
    for v in singles:
        out += struct.pack('<H', v)
    for b in leads:
        for t in range(256):
            v = 0
            try:
                s = bytes([b, t]).decode('cp932')
                if len(s) == 1 and ord(s) <= 0xFFFF:
                    v = ord(s)
            except UnicodeDecodeError:
                pass
            out += struct.pack('<H', v)
    with open(os.path.join(OUT, 'cp932.bin'), 'wb') as f:
        f.write(out)


def u8enc(c):
    return chr(c).encode('utf-8', 'surrogatepass')


def utf8_piece(r):
    k = r.randrange(14)
    if k <= 3:
        return bytes([r.randrange(0x20, 0x7F)])
    if k == 4:
        return u8enc(r.randrange(0x80, 0x800))
    if k == 5:
        c = r.randrange(0x800, 0x10000)
        while 0xD800 <= c <= 0xDFFF:
            c = r.randrange(0x800, 0x10000)
        return u8enc(c)
    if k == 6:
        return u8enc(r.randrange(0x10000, 0x110000))
    if k == 7:                                   # truncated valid sequence
        e = u8enc(r.choice([r.randrange(0x80, 0x800), r.randrange(0x800, 0xD800), r.randrange(0x10000, 0x110000)]))
        return e[:r.randrange(1, len(e))]
    if k == 8:                                   # overlongs
        return r.choice([bytes([0xC0 | r.randrange(2), 0x80 | r.randrange(64)]),
                         bytes([0xE0, 0x80 | r.randrange(32), 0x80 | r.randrange(64)]),
                         bytes([0xF0, 0x80 | r.randrange(16), 0x80 | r.randrange(64), 0x80 | r.randrange(64)])])
    if k == 9:                                   # encoded surrogates
        return bytes([0xED, 0xA0 | r.randrange(32), 0x80 | r.randrange(64)])
    if k == 10:                                  # above U+10FFFF
        return r.choice([bytes([0xF4, 0x90 | r.randrange(48), 0x80 | r.randrange(64), 0x80 | r.randrange(64)]),
                         bytes([0xF5 + r.randrange(3), 0x80 | r.randrange(64), 0x80 | r.randrange(64),
                                0x80 | r.randrange(64)])])
    if k == 11:                                  # lone continuation bytes
        return bytes([0x80 | r.randrange(64)] * r.randrange(1, 4))
    if k == 12:
        return bytes([r.choice([0x80, 0xBF, 0xC0, 0xC1, 0xC2, 0xDF, 0xE0, 0xED, 0xEF, 0xF0, 0xF4, 0xF5, 0xFE, 0xFF])])
    return bytes([r.randrange(256)])


def fmt_case(bs, cps):
    return '%s %s' % (bs.hex().upper() if bs else '.', ','.join('%X' % c for c in cps) if cps else '.')


def gen_utf8():
    r = random.Random(20261109)
    lines = ['# generated by tools/gen_testdata.py: strict UTF-8 vs Python surrogateescape']
    for i in range(1500):
        bs = b''.join(utf8_piece(r) for _ in range(r.randrange(0, 12)))
        s = bs.decode('utf-8', 'surrogateescape')
        cps = []
        for ch in s:
            c = ord(ch)
            cps.append(0x110000 + (c - 0xDC00) if 0xDC80 <= c <= 0xDCFF else c)
        lines.append(fmt_case(bs, cps))
    write_text('utf8.txt', lines)


def gen_utf16():
    r = random.Random(1200)
    lines = ['# generated by tools/gen_testdata.py: UTF-16 vs Python surrogatepass']
    for i in range(1500):
        units = []
        for _ in range(r.randrange(0, 10)):
            k = r.randrange(8)
            if k <= 1:
                units.append(r.randrange(0x20, 0x7F))
            elif k == 2:
                c = r.randrange(0x80, 0x10000)
                units.append(c if not 0xD800 <= c <= 0xDFFF else 0x4E2D)
            elif k == 3:
                c = r.randrange(0x10000, 0x110000) - 0x10000
                units += [0xD800 + (c >> 10), 0xDC00 + (c & 0x3FF)]
            elif k == 4:
                units.append(r.randrange(0xD800, 0xDC00))
            elif k == 5:
                units.append(r.randrange(0xDC00, 0xE000))
            elif k == 6:
                units.append(r.choice([0x0A, 0x0D, 0x00, 0xFEFF, 0xFFFF, 0xD7FF, 0xE000]))
            else:
                units.append(r.randrange(0x10000))
        for be in (0, 1):
            fmt = '>H' if be else '<H'
            bs = b''.join(struct.pack(fmt, u) for u in units)
            odd = r.randrange(4) == 0
            tail = bytes([r.randrange(256)]) if odd else b''
            s = bs.decode('utf-16-be' if be else 'utf-16-le', 'surrogatepass')
            cps = [0x120000 + ord(ch) if 0xD800 <= ord(ch) <= 0xDFFF else ord(ch) for ch in s]
            if odd:
                cps.append(0x110000 + tail[0])
            lines.append(('be ' if be else 'le ') + fmt_case(bs + tail, cps))
    write_text('utf16.txt', lines)


def gen_ucd_blocks():
    lines = ['# generated by tools/gen_testdata.py: per-block checksums of width, fold, upper, lower, word (Unicode %s)'
             % gen_ucd.unicodedata.unidata_version]
    for blk in range(0x110000 // 256):
        h = 0
        for c in range(blk * 256, blk * 256 + 256):
            for v in (gen_ucd.width(c), gen_ucd.fold(c), gen_ucd.upper(c), gen_ucd.lower(c), gen_ucd.is_word(c)):
                h = (h * 31 + v) & 0xFFFFFFFF
        lines.append('%04X %08X' % (blk, h))
    write_text('ucd_blocks.txt', lines)


def main():
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    gen_sbcs()
    gen_cp932()
    gen_utf8()
    gen_utf16()
    gen_ucd_blocks()
    print('wrote %s' % os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
