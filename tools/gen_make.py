#!/usr/bin/env python3
"""Generate the two build files from one table so the per-suite source lists stay identical:
  Makefile        NMAKE (VC6), CRLF          tests/Makefile  GNU make (Mac clang), LF
Edit the tables below and run:  python3 tools/gen_make.py
(After Wave 0 both Makefiles belong to the overseer; agents request changes in HANDOFF.md.)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CORE = """etypes emem estr esource ptree undo doc docbind marks codec cptables detect ucd ucdtables layout
lexer lexgen lexhtml lexmd regex rxvm rxbt rxpre search fif hexfmt edtype edlines edhex ini config session
faultfs fileops""".split()

WIN = """main frame tabs statusbar notifybar progress util cmdtable filecmds editcmds doccmds docio iothread
textview render hexview clip winenc fs_win32 dlgfind isearch fifpanel fifworker dlggoto dlgopts dlgmisc
sessmgr watch largefile selftest bench""".split()

# module groups (dependency closures, DESIGN 4.1)
G = {}
G['base'] = ['etypes', 'emem', 'estr']
G['src'] = G['base'] + ['esource']
G['pt'] = G['src'] + ['ptree']
G['ucd'] = G['base'] + ['ucd', 'ucdtables']
G['codec'] = G['src'] + ['ucd', 'ucdtables', 'codec', 'cptables']
G['detect'] = G['codec'] + ['detect']
G['doc'] = G['pt'] + ['undo'] + G['codec'] + ['detect', 'doc']
G['lex'] = G['ucd'] + ['lexer', 'lexgen', 'lexhtml', 'lexmd']
G['regex'] = G['codec'] + ['regex', 'rxvm', 'rxbt', 'rxpre']
G['search'] = G['regex'] + ['hexfmt', 'search']
G['ini'] = G['base'] + ['ini']
G['ed'] = G['doc'] + G['lex'] + ['layout', 'docbind', 'edtype']   # edtype: tab stops via LineLayout

FS = '@fs'          # fs_posix.cpp on the Mac, src/win/fs_win32.cpp on VC6

# suite -> core modules it links (plus @fs for file-system suites); order does not matter, duplicates removed
SUITES = [
    ('estr', G['base']),
    ('emem', G['src']),
    ('ptree', G['pt']),
    ('undo', G['pt'] + ['undo']),
    ('doc', G['doc']),
    ('marks', G['doc'] + ['marks'] + G['lex'] + ['docbind']),   # + DocLines test (T01_DOCBIND)
    ('codec', G['codec']),
    ('detect', G['detect']),
    ('ucd', G['ucd']),
    ('layout', G['codec'] + ['layout']),
    ('lexer', G['lex']),
    ('regex', G['regex']),
    ('search', G['search']),
    ('fif', G['search'] + ['detect', 'fif', FS]),
    ('hexfmt', G['codec'] + ['hexfmt']),
    ('edtype', G['ed']),
    ('edlines', G['ed'] + ['edlines']),
    ('edhex', G['ed'] + ['edhex']),
    ('ini', G['ini']),
    ('config', G['ini'] + G['codec'] + ['config']),
    ('session', G['ini'] + G['codec'] + ['session']),
    ('fileops', G['detect'] + ['ptree', 'ini', 'session', 'faultfs', 'fileops', FS]),
    ('winenc', G['codec'] + ['@winenc']),          # VC6 only
    ('adversarial', CORE + [FS]),
]
VC6_ONLY = {'winenc'}


def uniq(xs):
    out = []
    for x in xs:
        if x not in out:
            out.append(x)
    return out


def check():
    for name, mods in SUITES:
        for m in mods:
            if not m.startswith('@'):
                assert m in CORE, (name, m)
            assert os.path.exists(os.path.join(ROOT, 'tests', 't_%s.cpp' % name)), name
    for m in CORE:
        assert os.path.exists(os.path.join(ROOT, 'src', 'core', m + '.cpp')), m
    for m in WIN:
        assert os.path.exists(os.path.join(ROOT, 'src', 'win', m + '.cpp')), m


def wrap(items, indent, width=110):
    lines, cur = [], ''
    for it in items:
        if cur and len(cur) + 1 + len(it) > width:
            lines.append(cur)
            cur = indent + it
        else:
            cur = (cur + ' ' + it) if cur else it
    lines.append(cur)
    return ' \\\n'.join(lines)


# ---------------------------------------------------------------- NMAKE

def nmake():
    def o(m):
        if m == FS:
            return r'obj\fs_win32.obj'
        if m.startswith('@'):
            return 'obj\\%s.obj' % m[1:]
        return 'obj\\%s.obj' % m
    L = []
    A = L.append
    A('# Pica - NMAKE makefile (Visual C++ 6.0). GENERATED by tools/gen_make.py: edit the tables there and rerun.')
    A('# Build in the VM: ~/Documents/86box/samba/w98 build editor [target]')
    A('#   (all)            pica.exe              test         coretest.exe + run (C:\\PICATEST\\tmp)')
    A('#   t_<suite>        build + run one suite  obj\\<name>.obj  compile one source (per-file /W3 check)')
    A('#   testm            file-system suites against M:   release   clean rebuild into release\\Pica-1.0')
    A('#   clean            DEBUG=1: /Zi /Od /DE_DEBUG')
    A('APP = pica')
    A('CFLAGS = /nologo /W3 /O2 /G6 /MT /DWIN32 /D_WINDOWS /Isrc\\core /Isrc\\win /Ires')
    A('LFLAGS = /nologo')
    A('!IF "$(DEBUG)" == "1"')
    A('CFLAGS = /nologo /W3 /Zi /Od /G6 /MT /DWIN32 /D_WINDOWS /DE_DEBUG /Isrc\\core /Isrc\\win /Ires')
    A('LFLAGS = /nologo /debug')
    A('!ENDIF')
    A('TCFLAGS = $(CFLAGS) /Itests /DT01_DOCBIND')
    A('LIBS = user32.lib gdi32.lib kernel32.lib comctl32.lib comdlg32.lib shell32.lib advapi32.lib imm32.lib')
    A('TLIBS = kernel32.lib user32.lib')
    A('TRUN = -q -tmp C:\\PICATEST\\tmp -data tests\\data')
    A('')
    A('!IF !EXIST(obj)')
    A('!IF [mkdir obj]')
    A('!ENDIF')
    A('!ENDIF')
    A('')
    A('CORE_OBJS = ' + wrap([o(m) for m in CORE], '            '))
    A('')
    A('WIN_OBJS = ' + wrap([o(m) for m in WIN], '           '))
    A('')
    suites = [s for s, _ in SUITES]
    A('TEST_OBJS = obj\\t_main.obj ' + wrap(['obj\\t_%s.obj' % s for s in suites], '            '))
    A('')
    A('all: $(APP).exe')
    A('')
    A('$(APP).exe: $(CORE_OBJS) $(WIN_OBJS) obj\\pica.res')
    A('\tlink $(LFLAGS) /subsystem:windows /out:$(APP).exe @<<')
    A('$(CORE_OBJS) $(WIN_OBJS) obj\\pica.res $(LIBS)')
    A('<<')
    A('')
    A('obj\\pica.res: res\\pica.rc res\\*.rc2 res\\*.h res\\toolbar.bmp res\\pica.ico src\\langs\\*.lng src\\help\\help.md')
    A('\trc /r /i res /fo obj\\pica.res res\\pica.rc')
    A('')
    A('{src\\core\\}.cpp{obj\\}.obj::')
    A('\tcl $(CFLAGS) /c /Foobj\\ @<<')
    A('$<')
    A('<<')
    A('')
    A('{src\\win\\}.cpp{obj\\}.obj::')
    A('\tcl $(CFLAGS) /c /Foobj\\ @<<')
    A('$<')
    A('<<')
    A('')
    A('{tests\\}.cpp{obj\\}.obj::')
    A('\tcl $(TCFLAGS) /c /Foobj\\ @<<')
    A('$<')
    A('<<')
    A('')
    A('$(CORE_OBJS): src\\core\\*.h')
    A('$(WIN_OBJS): src\\core\\*.h src\\win\\*.h res\\*.h')
    A('$(TEST_OBJS): src\\core\\*.h tests\\tf.h')
    A('')
    A('# ---- coretest: every suite + fs_win32 + winenc (DESIGN 17.2)')
    A('test: coretest.exe')
    A('\tcoretest.exe $(TRUN)')
    A('')
    A('testm: coretest.exe')
    A('\tcoretest.exe fileops fif -q -tmp M:\\dev\\editor\\tests\\tmp -data tests\\data')
    A('')
    A('coretest.exe: $(CORE_OBJS) obj\\fs_win32.obj obj\\winenc.obj $(TEST_OBJS)')
    A('\tlink $(LFLAGS) /subsystem:console /out:coretest.exe @<<')
    A('$(CORE_OBJS) obj\\fs_win32.obj obj\\winenc.obj $(TEST_OBJS) $(TLIBS)')
    A('<<')
    A('')
    A('# ---- per-suite programs: only the sources that suite needs (same lists as tests/Makefile)')
    for name, mods in SUITES:
        objs = uniq([o(m) for m in mods])
        var = 'SU_%s' % name.upper()
        A('%s = %s' % (var, wrap(objs, '        ')))
        A('t_%s: obj\\t_%s.exe' % (name, name))
        A('\tobj\\t_%s.exe $(TRUN)' % name)
        A('obj\\t_%s.exe: $(%s) obj\\tm_%s.obj obj\\t_%s.obj' % (name, var, name, name))
        A('\tlink $(LFLAGS) /subsystem:console /out:obj\\t_%s.exe @<<' % name)
        A('$(%s) obj\\tm_%s.obj obj\\t_%s.obj $(TLIBS)' % (var, name, name))
        A('<<')
        A('obj\\tm_%s.obj: tests\\t_main.cpp tests\\tf.h src\\core\\*.h' % name)
        A('\tcl $(TCFLAGS) /DTF_SUITE=%s /c /Foobj\\tm_%s.obj tests\\t_main.cpp' % (name, name))
        A('')
    A('# ---- release (T18): clean rebuild, then release\\Pica-1.0 holds exactly pica.exe + README.TXT.')
    A('# The old folder is deleted first: running the exe from there writes pica.ini, session*.ini, backup\\ and')
    A('# "Pica Help.md" next to it, and none of that may ship. Zip + setup copy: tools/mkzip.sh on the Mac.')
    A('VER = 1.0')
    A('REL = release\\Pica-$(VER)')
    A('# FORCE: the release\\ folder exists after the first run, so nmake would call the target up to date')
    A('release: FORCE')
    A('\t$(MAKE) /nologo clean')
    A('\t$(MAKE) /nologo all')
    A('\t@if not exist release\\nul mkdir release')
    A('\t@if exist $(REL)\\nul deltree /y $(REL) > nul')
    A('\tmkdir $(REL)')
    A('\tcopy $(APP).exe $(REL)\\$(APP).exe')
    A('\tcopy README.TXT $(REL)\\README.TXT')
    A('\tdir $(REL)')
    A('')
    A('FORCE:')
    A('')
    A('clean:')
    A('\t-del obj\\*.obj')
    A('\t-del obj\\*.exe')
    A('\t-del obj\\*.res')
    A('\t-del obj\\*.pdb')
    A('\t-del obj\\*.idb')
    A('\t-del $(APP).exe')
    A('\t-del coretest.exe')
    A('\t-del *.pdb')
    A('\t-del *.ilk')
    A('')
    return '\n'.join(L).replace('\r\n', '\n').replace('\n', '\r\n')


# ---------------------------------------------------------------- GNU make (Mac)

def gmake():
    def src(m):
        if m == FS:
            return 'fs_posix.cpp'
        return '../src/core/%s.cpp' % m
    L = []
    A = L.append
    A('# Pica - Mac unit tests (GNU make, Apple clang). GENERATED by tools/gen_make.py: edit the tables there and rerun.')
    A('#   make -C tests            = check: lint + strict and ASan/UBSan runs of all suites (coretest)')
    A('#   make -C tests <suite>    one suite, both builds, only the sources that suite needs')
    A('#   make -C tests mac        C++11 extras in tests/mac/*.cpp (each a standalone program)')
    A('#   make -C tests data       regenerate tests/data with tools/gen_testdata.py')
    A('#   make -C tests clean')
    A('CXX = clang++')
    A('WARN = -std=c++98 -pedantic -Wall -Wextra -Werror -Wshadow -fno-exceptions -fno-rtti')
    A('CPPFLAGS = -DE_DEBUG -DT01_DOCBIND -I../src/core -I. -MMD -MP')
    A('OPT_strict = -O2')
    A('OPT_asan = -O1 -g -fno-omit-frame-pointer -fsanitize=address,undefined -fno-sanitize-recover=all')
    A('LD_strict =')
    A('LD_asan = -fsanitize=address,undefined')
    A('B = build')
    A('RUN = -q -data data -tmp tmp')
    A('export ASAN_OPTIONS = detect_leaks=0')
    A('')
    mac_suites = [(s, m) for s, m in SUITES if s not in VC6_ONLY]
    A('SUITES = ' + wrap([s for s, _ in mac_suites], '         '))
    A('CORE_SRCS = ' + wrap([src(m) for m in CORE], '            '))
    A('')
    A('.PHONY: check lint coretest mac data clean $(SUITES)')
    A('')
    A('check: lint coretest')
    A('')
    A('lint:')
    A('\tpython3 ../tools/lint.py')
    A('')
    A('obj = $(addprefix $(B)/$(1)/,$(notdir $(2:.cpp=.o)))')
    A('')
    A('ALL_SRCS = $(CORE_SRCS) fs_posix.cpp t_main.cpp $(addprefix t_,$(addsuffix .cpp,$(SUITES)))')
    A('')
    A('coretest: $(B)/strict/coretest $(B)/asan/coretest')
    A('\t$(B)/strict/coretest $(RUN)')
    A('\t$(B)/asan/coretest $(RUN)')
    A('')
    for mode in ('strict', 'asan'):
        A('$(B)/%s/coretest: $(call obj,%s,$(ALL_SRCS))' % (mode, mode))
        A('\t$(CXX) $(OPT_%s) $(LD_%s) -o $@ $^' % (mode, mode))
        A('$(B)/%s/%%.o: ../src/core/%%.cpp | $(B)/%s' % (mode, mode))
        A('\t$(CXX) $(WARN) $(CPPFLAGS) $(OPT_%s) -c $< -o $@' % mode)
        A('$(B)/%s/%%.o: %%.cpp | $(B)/%s' % (mode, mode))
        A('\t$(CXX) $(WARN) $(CPPFLAGS) $(OPT_%s) -c $< -o $@' % mode)
        A('$(B)/%s:' % mode)
        A('\tmkdir -p $@')
        A('')
    A('# Each suite builds in its own folder (build/su_<suite>/...) so parallel agents never race on shared objects.')
    for name, mods in mac_suites:
        srcs = uniq([src(m) for m in mods])
        var = 'SU_%s' % name
        A('%s = %s' % (var, wrap(srcs + ['t_%s.cpp' % name], '         ')))
        A('%s: $(B)/su_%s/strict/t_%s $(B)/su_%s/asan/t_%s' % (name, name, name, name, name))
        A('\t$(B)/su_%s/strict/t_%s $(RUN)' % (name, name))
        A('\t$(B)/su_%s/asan/t_%s $(RUN)' % (name, name))
        for mode in ('strict', 'asan'):
            d = '$(B)/su_%s/%s' % (name, mode)
            A('%s/t_%s: $(call obj,su_%s/%s,$(%s)) %s/tm_%s.o' % (d, name, name, mode, var, d, name))
            A('\t$(CXX) $(OPT_%s) $(LD_%s) -o $@ $^' % (mode, mode))
            A('%s/tm_%s.o: t_main.cpp | %s' % (d, name, d))
            A('\t$(CXX) $(WARN) $(CPPFLAGS) $(OPT_%s) -DTF_SUITE=%s -c $< -o $@' % (mode, name))
            A('%s/%%.o: ../src/core/%%.cpp | %s' % (d, d))
            A('\t$(CXX) $(WARN) $(CPPFLAGS) $(OPT_%s) -c $< -o $@' % mode)
            A('%s/%%.o: %%.cpp | %s' % (d, d))
            A('\t$(CXX) $(WARN) $(CPPFLAGS) $(OPT_%s) -c $< -o $@' % mode)
            A('%s:' % d)
            A('\tmkdir -p $@')
        A('')
    A('MAC_SRCS = $(wildcard mac/*.cpp)')
    A('MAC_BINS = $(patsubst mac/%.cpp,$(B)/mac/%,$(MAC_SRCS))')
    A('mac: $(MAC_BINS)')
    A('\t@if [ -z "$(MAC_BINS)" ]; then echo "tests/mac: no programs yet"; fi')
    A('\t@for b in $(MAC_BINS); do echo "== $$b"; $$b || exit 1; done')
    A('$(B)/mac/%: mac/%.cpp $(CORE_SRCS) fs_posix.cpp')
    A('\tmkdir -p $(B)/mac')
    A('\t$(CXX) -std=c++11 -O2 -Wall -Wextra -DE_DEBUG -I../src/core -I. -o $@ $< $(CORE_SRCS) fs_posix.cpp')
    A('')
    A('data:')
    A('\t@if [ -f ../tools/gen_testdata.py ]; then python3 ../tools/gen_testdata.py; else echo "tools/gen_testdata.py: not written yet (T02)"; fi')
    A('')
    A('clean:')
    A('\trm -rf $(B) tmp')
    A('')
    A('-include $(wildcard $(B)/*/*.d $(B)/*/*/*.d)')
    A('')
    return '\n'.join(L)


if __name__ == '__main__':
    check()
    with open(os.path.join(ROOT, 'Makefile'), 'wb') as f:
        f.write(nmake().encode('ascii'))
    with open(os.path.join(ROOT, 'tests', 'Makefile'), 'wb') as f:
        f.write(gmake().encode('ascii'))
    print('wrote Makefile and tests/Makefile')
