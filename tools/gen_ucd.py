#!/usr/bin/env python3
"""Generate src/core/ucdtables.cpp: Unicode property tables for Pica (DESIGN 6.11). Owner: T02.
  python3 tools/gen_ucd.py

Properties (from Python's unicodedata and str case methods; deterministic for a given Python version):
  width  0 = Mn, Me, Cf (except U+00AD and the visible prepended concatenation marks), Hangul medial/final jamo
           U+1160-11FF; 2 = East Asian Wide/Fullwidth (plus the unassigned CJK ideograph blocks); else 1
  fold   simple case folding (CaseFolding C+S): str.casefold() if it is one char, else str.lower() if one char,
         else unchanged (so U+1E9E -> U+00DF, U+1F88 -> U+1F80, U+00DF and U+0130 stay)
  upper  simple uppercase: str.upper() if one char, else str.title() if one char, else unchanged
  lower  simple lowercase: str.lower() if one char (U+0130 -> 'i'), else unchanged
  word   letters (L*), marks (M*), decimal digits (Nd), connector punctuation (Pc)
Space (White_Space) and drawable ranges are fixed lists in ucd.cpp.
tools/gen_testdata.py imports this module for the per-block checksums in tests/data/codec/ucd_blocks.txt.
Layout of the tables: src/core/ucd_tables.h.
"""
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'core', 'ucdtables.cpp')
MAXCP = 0x110000

VISIBLE_CF = {0x00AD, 0x0600, 0x0601, 0x0602, 0x0603, 0x0604, 0x0605, 0x06DD, 0x070F, 0x08E2, 0x110BD, 0x110CD}
CJK_WIDE = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]


def width(c):
    if 0xD800 <= c <= 0xDFFF:
        return 1
    ch = chr(c)
    cat = unicodedata.category(ch)
    if c not in VISIBLE_CF and (cat in ('Mn', 'Me', 'Cf') or 0x1160 <= c <= 0x11FF):
        return 0
    if cat == 'Cn':                      # Python 3.9 reports 'F' for unassigned code points: ignore it
        for lo, hi in CJK_WIDE:
            if lo <= c <= hi:
                return 2
        return 1
    if unicodedata.east_asian_width(ch) in ('W', 'F'):
        return 2
    return 1


def fold(c):
    if 0xD800 <= c <= 0xDFFF:
        return c
    ch = chr(c)
    f = ch.casefold()
    if len(f) == 1:
        return ord(f)
    lo = ch.lower()
    if len(lo) == 1:
        return ord(lo)
    return c


def upper(c):
    if 0xD800 <= c <= 0xDFFF:
        return c
    ch = chr(c)
    u = ch.upper()
    if len(u) == 1:
        return ord(u)
    t = ch.title()
    if len(t) == 1:
        return ord(t)
    return c


def lower(c):
    if 0xD800 <= c <= 0xDFFF:
        return c
    if c == 0x0130:
        return 0x69
    lo = chr(c).lower()
    if len(lo) == 1:
        return ord(lo)
    return c


def is_word(c):
    if 0xD800 <= c <= 0xDFFF:
        return 0
    cat = unicodedata.category(chr(c))
    return 1 if (cat[0] in 'LM' or cat in ('Nd', 'Pc')) else 0


def ranges(pred):
    out = []
    start = None
    for c in range(MAXCP):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, MAXCP - 1))
    return out


def case_runs(fn):
    """Runs (lo, count, stride, delta): lo + i*stride -> lo + i*stride + delta for i < count."""
    keys = [c for c in range(MAXCP) if fn(c) != c]
    runs = []
    i = 0
    while i < len(keys):
        lo = keys[i]
        d = fn(lo) - lo
        count = 1
        stride = 0
        j = i + 1
        while j < len(keys) and count < 65535:
            k = keys[j]
            if fn(k) - k != d:
                break
            if stride == 0:
                if k - lo in (1, 2):
                    stride = k - lo
                else:
                    break
            elif k != lo + count * stride:
                break
            count += 1
            j += 1
        runs.append((lo, count, stride or 1, d))
        i = j
    return runs


def emit_ranges(w, name, rs):
    w('const UcRange %s[] = {' % name)
    for i in range(0, len(rs), 6):
        w('  ' + ' '.join('{ 0x%05X, 0x%05X },' % r for r in rs[i:i + 6]))
    w('};')
    w('const u32 %s_n = %d;' % (name, len(rs)))
    w('')


def emit_case(w, name, runs):
    w('const UcCase %s[] = {' % name)
    for i in range(0, len(runs), 4):
        w('  ' + ' '.join('{ 0x%05X, %d, %d, 0, %d },' % r for r in runs[i:i + 4]))
    w('};')
    w('const u32 %s_n = %d;' % (name, len(runs)))
    w('')


def emit_lat(w, ctype, name, vals, fmt):
    w('const %s %s[256] = {' % (ctype, name))
    for i in range(0, 256, 16):
        w('  ' + ', '.join(fmt % v for v in vals[i:i + 16]) + ',')
    w('};')
    w('')


def main():
    lines = []
    w = lines.append
    w('// ucdtables.cpp - GENERATED by tools/gen_ucd.py from Python %s unicodedata (Unicode %s). Do not edit.'
      % (sys.version.split()[0], unicodedata.unidata_version))
    w('// Width, simple case mappings and word class (DESIGN 6.11). Layout: ucd_tables.h. Owner: T02.')
    w('#include "ucd_tables.h"')
    w('')
    for c in range(0x300):
        if width(c) != 1:
            raise SystemExit('width fast path broken at U+%04X' % c)
    for c in range(0x1100):
        if width(c) == 2:
            raise SystemExit('width-2 fast path broken at U+%04X' % c)
    emit_lat(w, 'u16', 'g_uc_lat_fold', [fold(c) for c in range(256)], '0x%04X')
    emit_lat(w, 'u16', 'g_uc_lat_upper', [upper(c) for c in range(256)], '0x%04X')
    emit_lat(w, 'u16', 'g_uc_lat_lower', [lower(c) for c in range(256)], '0x%04X')
    emit_lat(w, 'u8', 'g_uc_lat_word', [is_word(c) for c in range(256)], '%d')
    emit_ranges(w, 'g_uc_w0', ranges(lambda c: width(c) == 0))
    emit_ranges(w, 'g_uc_w2', ranges(lambda c: width(c) == 2))
    emit_ranges(w, 'g_uc_word', ranges(lambda c: is_word(c) == 1))
    emit_case(w, 'g_uc_fold', case_runs(fold))
    emit_case(w, 'g_uc_upper', case_runs(upper))
    emit_case(w, 'g_uc_lower', case_runs(lower))
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %s' % os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
