#!/usr/bin/env python3
"""Generate src/core/cptables.cpp: single-byte code page tables for Pica (DESIGN 6.9). Owner: T02.
  python3 tools/gen_cptables.py

For every code page: the decode table of the high half (bytes 0x80-0xFF; 0 = byte undefined in that code page) and a
reverse table sorted by code point (code point -> byte) for the defined high bytes. Bytes 0x00-0x7F decode to
themselves in every table (the script checks this; for OEM pages 0x00-0x1F are controls, as in Python's codecs).
The data comes from Python's codecs module, so the output is deterministic for a given Python version.
Struct layout: src/core/codec_tables.h.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'core', 'cptables.cpp')

# DESIGN 6.9 list, plus the OEM pages 720/737/775/858 so OEM text on Arabic/Greek/Baltic systems decodes too.
CODEPAGES = [1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258, 874,
             437, 720, 737, 775, 850, 852, 855, 857, 858, 860, 861, 862, 863, 865, 866, 869,
             20866, 21866] + list(range(28591, 28600)) + [28605]


def pyname(cp):
    if cp == 20866:
        return 'koi8_r'
    if cp == 21866:
        return 'koi8_u'
    if 28591 <= cp <= 28599:
        return 'iso8859_%d' % (cp - 28590)
    if cp == 28605:
        return 'iso8859_15'
    return 'cp%d' % cp


def decode_table(cp):
    """Returns a list of 256 code points (None = undefined byte)."""
    name = pyname(cp)
    out = []
    for b in range(256):
        try:
            s = bytes([b]).decode(name)
        except UnicodeDecodeError:
            out.append(None)
            continue
        if len(s) != 1:
            raise SystemExit('cp%d byte %02X decodes to %d chars' % (cp, b, len(s)))
        out.append(ord(s))
    return out


def check(cp, tbl):
    for b in range(128):
        if tbl[b] != b:
            raise SystemExit('cp%d: byte %02X is not ASCII-identical' % (cp, b))
    seen = {}
    for b in range(128, 256):
        v = tbl[b]
        if v is None:
            continue
        if v < 0x80 or v > 0xFFFF:
            raise SystemExit('cp%d: byte %02X -> U+%04X outside 0x80-0xFFFF' % (cp, b, v))
        if v in seen:
            raise SystemExit('cp%d: bytes %02X and %02X both map to U+%04X' % (cp, seen[v], b, v))
        seen[v] = b


def main():
    lines = []
    w = lines.append
    w('// cptables.cpp - GENERATED by tools/gen_cptables.py from Python %s codecs. Do not edit.' % sys.version.split()[0])
    w('// Single-byte code page tables (DESIGN 6.9): high-half decode table (0 = undefined byte) and the reverse table')
    w('// sorted by code point. Bytes 0x00-0x7F decode to themselves in every table. Layout: codec_tables.h.')
    w('// Owner: T02.')
    w('#include "codec_tables.h"')
    w('')
    entries = []
    for cp in CODEPAGES:
        tbl = decode_table(cp)
        check(cp, tbl)
        hi = [tbl[b] or 0 for b in range(128, 256)]
        rev = sorted((tbl[b], b) for b in range(128, 256) if tbl[b] is not None)
        w('static const u16 k_hi_%d[128] = {' % cp)
        for i in range(0, 128, 12):
            w('  ' + ', '.join('0x%04X' % v for v in hi[i:i + 12]) + ',')
        w('};')
        if rev:
            w('static const u16 k_rc_%d[%d] = {' % (cp, len(rev)))
            for i in range(0, len(rev), 12):
                w('  ' + ', '.join('0x%04X' % v for v, _ in rev[i:i + 12]) + ',')
            w('};')
            w('static const u8 k_rb_%d[%d] = {' % (cp, len(rev)))
            for i in range(0, len(rev), 16):
                w('  ' + ', '.join('0x%02X' % b for _, b in rev[i:i + 16]) + ',')
            w('};')
        entries.append((cp, len(rev)))
        w('')
    w('const SbcsTable g_sbcs_tables[] = {')
    for cp, n in entries:
        w('  { %d, %d, k_hi_%d, k_rc_%d, k_rb_%d },' % (cp, n, cp, cp, cp))
    w('};')
    w('const u32 g_sbcs_table_count = %d;' % len(entries))
    w('')
    data = '\n'.join(lines)
    with open(OUT, 'w', newline='\n') as f:
        f.write(data)
    print('wrote %s (%d code pages)' % (os.path.relpath(OUT, ROOT), len(entries)))


if __name__ == '__main__':
    main()
